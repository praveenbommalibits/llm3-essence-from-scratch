RL_PROMPT_ROWS = [
    {"prompt": "What is 12 + 8?", "gold": 20.0},
    {"prompt": "What is 7 * 6?", "gold": 42.0},
    {"prompt": "A box has 9 pens and you add 4 more. How many pens are there?", "gold": 13.0},
]


def write_jsonl(rows: list[dict], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
    print(f"wrote {len(rows)} rows -> {path}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out_dir", default="data/samples")
    args = parser.parse_args()

    out_dir = Path(args.out_dir)
    write_jsonl(PRETRAIN_ROWS, out_dir / "pretrain_text.jsonl")
    write_jsonl(SFT_ROWS, out_dir / "sft_custom.jsonl")
    write_jsonl(PREFERENCE_ROWS, out_dir / "preferences_custom.jsonl")
    write_jsonl(RL_PROMPT_ROWS, out_dir / "rl_prompts_custom.jsonl")

    rel = os.path.relpath(out_dir)
    print(f"\nSample label files are ready in {rel}")


if __name__ == "__main__":
    main()
